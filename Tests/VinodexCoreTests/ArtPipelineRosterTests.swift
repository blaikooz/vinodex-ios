    @Test("every UI glyph is drawn, typed and bundled")
    func glyphRosterIsComplete() throws {
        let wanted = Set(UIGlyph.allCases.map(\.rawValue))
        #expect(wanted.count == UIGlyph.allCases.count, "two UIGlyph cases share a raw value")

        let onDisk = try Self.pngStems("art", "icons", "chrome", "glyphs")
        #expect(
            onDisk == wanted,
            """
            UIGlyph and art/icons/chrome/glyphs/ disagree — \
            drawn but not typed (these ship nowhere): \(onDisk.subtracting(wanted).sorted()), \
            typed but not drawn: \(wanted.subtracting(onDisk).sorted())
            """
        )

        // `artStem`, restated — the prefix `import-glyph-art.py` writes. Two
        // languages, one expression, held together here exactly as
        // `ChassisSkin.stickerStem` is.
        let expected = Set(UIGlyph.allCases.map(\.artStem))
        let bundled = try Self.pngStems("Sources", "VinodexUI", "Resources", "GlyphArt")
        #expect(
            bundled == expected,
            "Resources/GlyphArt holds \(bundled.sorted()), UIGlyph asks for \(expected.sorted())"
        )

        // The backlog, one way only, because the other way cannot be checked
        // from Core: whether a stem has a call site is a fact about VinodexUI.
        // What *is* checkable is that the list names real glyphs — a typo here
        // would silently shrink the parked set and make a genuine gap look
        // deliberate.
        #expect(
            UIGlyph.unwired.isSubset(of: Set(UIGlyph.allCases)),
            "UIGlyph.unwired names cases that do not exist"
        )
        // And that no tier's shield is on it. This is the half of the ladder
        // wiring a roster can see: `PassportTier.glyph` is exhaustive, so every
        // rung has a shield.
        for tier in PassportTier.allCases {
            #expect(
                !UIGlyph.unwired.contains(tier.glyph),
                "\(tier.displayName) draws \(tier.glyph.artStem), which is parked as unwired"
            )
        }
        // **This line used to read the other way** — `unwired.contains(.level5)`,
        // with the message "level5 has a rung now — take it off the list". It
        // got one in 0.8.9b (WINE MONK), so the assertion flips, which is the
        // whole behaviour a two-way gate is for: the parked list cannot rot into
        // an excuse, because coming *off* it is as checked as going on.
        //
        // All five shields are now spoken for, so the stronger statement is
        // available and worth making: no `level*` glyph is parked at all.
        for glyph in UIGlyph.allCases where glyph.rawValue.hasPrefix("level") {
            #expect(
                !UIGlyph.unwired.contains(glyph),
                "\(glyph.artStem) is parked, but every numbered shield has a rung now"
            )
        }
        #expect(
            Set(PassportTier.allCases.map(\.glyph)).count == PassportTier.allCases.count,
            "two rungs share a shield"
        )
    }

