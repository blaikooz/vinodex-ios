import Foundation
import Testing
// The stamp roster (0.8.5, F1) is the first check here that compares a script
// against a *type* rather than against another script — `StampCatalog` and
// `BackPlateDecal` both live in Core, so the stems the app asks for can be read
// from the app rather than restated in a list this suite would then have to
// police as well.
@testable import VinodexCore

/// The art pipeline's four rosters name the same importers (0.7.5, A027).
///
/// **They had already drifted, twice, and nothing said so.** `import-stamp-art.py`
/// was in `rasterize-icons.sh`'s roster from 0.6.4 and never in `verify-art.py`'s
/// `IMPORTERS`, so `StampArt` was generated by `npm run icons` and unverifiable by
/// `npm run icons:verify` for two releases. `import-logo-art.py` shipped in 0.7.5
/// (A5) in *neither*, plus no `package.json` script — the screensaver wordmark was
/// reproducible from `art/icons/chrome/logo/` only by someone who knew the file existed and
/// ran it by hand. Both are the same fault: a roster is a hand-kept list, and a
/// hand-kept list of files is exactly what goes stale when a sixth file lands.
///
/// So the list of importers *on disk* is the authority here, and the three places
/// that enumerate them are checked against it. Adding a seventh importer fails this
/// suite until it is wired everywhere, which is the whole point — the alternative is
/// finding out two releases later, as above.
///
/// **Ten as of 0.8.2**, which is the suite earning its keep twice in one batch:
/// `import-footer-art.py` and `import-cartridge-art.py` landed together, and
/// each one had to be added to the rasteriser, to `IMPORTERS`, to `DIRS` and to
/// `package.json` before this went green. That is eight edits nobody would have
/// remembered from the shape of the task, which was "wire up some new art".
/// **Thirteen as of 0.8.9a**, and the two that landed together (`import-glyph-art.py`
/// and `import-vino-art.py`) each needed all six places, which is twelve edits
/// nobody would have remembered from the shape of the task — again "wire up some
/// new art". The same batch moved every master under `art/icons/` into
/// `entries/` and `chrome/`, which is a seventh place per importer and the one
/// this suite could not have caught: a source path is read at *import* time, so
/// a stale one fails loudly on the next `npm run icons` rather than silently.
/// `npm run icons:verify` is what proved that move inert — 379 files identical
/// before a single new asset was added.
///
/// There is a fifth place these two also needed — `PixelArtLoader.subdirectories`
/// — which this suite cannot see, because it lives in `VinodexUI`. That gap is
/// real and the clean `xtool` build is what covers it: a directory the loader
/// never searches yields a nil image, and nil images are silent.
///
/// **That last paragraph was wrong, and a sixth place has since appeared.** The
/// gap was not that `VinodexUI` is uncompilable here — this suite never compiles
/// anything it checks. It reads shell and Python off disk through `#filePath`,
/// and `EntryVisual.swift` is a text file by the same measure. The clean `xtool`
/// build does *not* cover it either: an unsearched directory yields nil, nil is
/// silent, and the build is green. The `Bundle layout` section below closes it,
/// and closes the sixth place with it — `Package.swift` now names each bundled
/// directory by hand (a codesign requirement, see there), which turns a list
/// that used to maintain itself into one more hand-kept roster of exactly the
/// kind this suite was written for. It had already drifted by three entries on
/// arrival.
///
/// **Why a Swift test for shell and Python.** It is the only gate that runs on every
/// push. `npm run icons` needs network access and `rsvg-convert`; `icons:verify`
/// needs Pillow; neither runs in CI. `swift test` does, on every branch. The same
/// argument that put `assertAssetsExist` in the generator rather than in
/// `verify-art.py` puts this here rather than in either script. Reached through
/// `#filePath` exactly as `LogoLayerTests` reaches the wordmark PNGs.
@Suite("Art pipeline rosters")
struct ArtPipelineRosterTests {
    /// `Tests/VinodexCoreTests/<this file>` -> the package root.
    private static var repoRoot: URL {
        URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent()
            .deletingLastPathComponent()
            .deletingLastPathComponent()
    }

    private static func read(_ components: String...) throws -> String {
        var url = repoRoot
        for component in components { url.appendPathComponent(component) }
        return try String(contentsOf: url, encoding: .utf8)
    }

    /// Every `"..."` run in `text`, in order.
    ///
    /// Enough of a parser for the shapes involved — a Python tuple of literals, a
    /// `DIRS = (...)` line, an `output_dir(ROOT, "X")` call — and it needs no regex
    /// engine, which keeps the test identical on Linux and Darwin.
    ///
    /// It does **not** understand comments, and callers that read a heavily
    /// annotated list must account for that — see `loaderSearchPath`.
    private static func quoted(_ text: String) -> [String] {
        text.split(separator: "\"", omittingEmptySubsequences: false)
            .enumerated()
            .filter { $0.offset % 2 == 1 }
            .map { String($0.element) }
    }

    /// The text between the first `open` at or after `from` and the next `close`.
    private static func slice(_ text: String, from marker: String, to close: Character) -> String? {
        guard let start = text.range(of: marker) else { return nil }
        let rest = text[start.upperBound...]
        guard let end = rest.firstIndex(of: close) else { return nil }
        return String(rest[..<end])
    }

    // MARK: - The authority

    /// `scripts/import-*-art.py`, the set every roster below must reproduce.
    private static var importersOnDisk: Set<String> {
        get throws {
            let scripts = repoRoot.appendingPathComponent("scripts")
            let names = try FileManager.default.contentsOfDirectory(atPath: scripts.path)
            return Set(
                names.filter { $0.hasPrefix("import-") && $0.hasSuffix("-art.py") }
            )
        }
    }

    // MARK: - The three rosters

    /// The `for importer in ... ; do` line that runs the drawn-art half.
    private static var rasterizeRoster: Set<String> {
        get throws {
            let text = try read("scripts", "rasterize-icons.sh")
            guard let line = slice(text, from: "for importer in ", to: ";") else { return [] }
            return Set(line.split(whereSeparator: \.isWhitespace).map(String.init))
        }
    }

    /// `verify-art.py`'s `IMPORTERS` tuple.
    private static var verifyRoster: Set<String> {
        get throws {
            let text = try read("scripts", "verify-art.py")
            guard let tuple = slice(text, from: "IMPORTERS = (", to: ")") else { return [] }
            return Set(quoted(tuple))
        }
    }

    /// `verify-art.py`'s `DIRS` tuple — the bundle directories it diffs.
    private static var verifyDirs: Set<String> {
        get throws {
            let text = try read("scripts", "verify-art.py")
            guard let tuple = slice(text, from: "DIRS = (", to: ")") else { return [] }
            return Set(quoted(tuple))
        }
    }

    /// The npm scripts, by the command each one runs.
    private static var npmCommands: [String] {
        get throws {
            let data = try Data(contentsOf: repoRoot.appendingPathComponent("package.json"))
            let json = try JSONSerialization.jsonObject(with: data) as? [String: Any]
            let scripts = json?["scripts"] as? [String: String] ?? [:]
            return Array(scripts.values)
        }
    }

    // MARK: - Tests

    @Test("the importer set is not empty, so a parse failure cannot pass silently")
    func rostersParse() throws {
        let onDisk = try Self.importersOnDisk
        let rasterize = try Self.rasterizeRoster
        let verify = try Self.verifyRoster
        let dirs = try Self.verifyDirs
        #expect(onDisk.count >= 6, "found only \(onDisk.sorted()) under scripts/")
        #expect(!rasterize.isEmpty, "could not parse rasterize-icons.sh's roster")
        #expect(!verify.isEmpty, "could not parse verify-art.py's IMPORTERS")
        #expect(!dirs.isEmpty, "could not parse verify-art.py's DIRS")
    }

    @Test("rasterize-icons.sh runs every importer in scripts/")
    func rasterizeCoversAll() throws {
        let onDisk = try Self.importersOnDisk
        let roster = try Self.rasterizeRoster
        #expect(
            roster == onDisk,
            """
            rasterize-icons.sh's roster and scripts/import-*-art.py disagree — \
            not run: \(onDisk.subtracting(roster).sorted()), \
            named but absent: \(roster.subtracting(onDisk).sorted())
            """
        )
    }

    @Test("verify-art.py verifies every importer rasterize-icons.sh runs")
    func verifyMatchesRasterize() throws {
        let rasterize = try Self.rasterizeRoster
        let verify = try Self.verifyRoster
        #expect(
            rasterize == verify,
            """
            the two rosters have drifted (A027) — \
            generated but not verified: \(rasterize.subtracting(verify).sorted()), \
            verified but not generated: \(verify.subtracting(rasterize).sorted())
            """
        )
    }

    /// Each importer declares its bundle directory as `output_dir(<root>, "Name")`
    /// — the one call `ART_OUT` redirects — so the destinations are readable from
    /// the source rather than restated. `DIRS` must cover all of them, or an
    /// importer's output is regenerated into the temp tree and then never compared,
    /// which is the shape `StampArt` shipped in.
    @Test("verify-art.py's DIRS covers every importer's output directory")
    func verifyDirsCoverOutputs() throws {
        var declared: Set<String> = []
        for importer in try Self.importersOnDisk.sorted() {
            let text = try Self.read("scripts", importer)
            guard let call = Self.slice(text, from: "output_dir(", to: ")") else {
                Issue.record("\(importer) does not route its destination through art_common.output_dir")
                continue
            }
            guard let name = Self.quoted(call).last else {
                Issue.record("\(importer)'s output_dir call names no directory: \(call)")
                continue
            }
            declared.insert(name)
        }
        let dirs = try Self.verifyDirs
        #expect(
            declared.subtracting(dirs).isEmpty,
            "importers write directories verify-art.py never diffs: \(declared.subtracting(dirs).sorted())"
        )
        #expect(
            dirs.subtracting(declared).isEmpty,
            "verify-art.py's DIRS names directories no importer writes: \(dirs.subtracting(declared).sorted())"
        )
    }

    // MARK: - The bundle layout (merged from the Aug 5 Xcode/codesign branch)

    /// Directories that exist under `Sources/VinodexUI/Resources/`.
    private static var bundledDirectoriesOnDisk: Set<String> {
        get throws {
            var url = repoRoot
            for component in ["Sources", "VinodexUI", "Resources"] {
                url.appendPathComponent(component)
            }
            let names = try FileManager.default.contentsOfDirectory(
                at: url,
                includingPropertiesForKeys: [.isDirectoryKey]
            )
            return Set(
                names
                    .filter { (try? $0.resourceValues(forKeys: [.isDirectoryKey]).isDirectory) == true }
                    .map(\.lastPathComponent)
            )
        }
    }

    /// `Package.swift`'s `VinodexUI` resource list, less the `Resources/` prefix
    /// each `.copy` path carries.
    ///
    /// Sliced from the `VinodexUI` target rather than the whole file, because
    /// `VinodexCore`'s list above it names eight JSON *files* by the same
    /// `.copy("Resources/...")` spelling and would otherwise be counted in.
    ///
    /// **Two slices, not one**, and the reason is worth writing down because the
    /// one-slice version parsed to an empty set and the empty set is what a
    /// silently-passing gate looks like. `slice(_:from:to:)` stops at the first
    /// closing character, and the first `]` after `name: "VinodexUI"` closes
    /// `dependencies: ["VinodexCore"]`, not the resource list. So this narrows to
    /// the target first and to `resources: [` second. The `!declared.isEmpty`
    /// assertion below is what caught it, and it is there for exactly this — the
    /// same reason `rostersParse` exists one section up.
    private static var packageResourceDirectories: Set<String> {
        get throws {
            let text = try read("Package.swift")
            // Everything from the target's name onward — no closing character,
            // because the first `)` after it belongs to a `.copy(...)` call
            // inside the very list being looked for.
            guard let name = text.range(of: "name: \"VinodexUI\"") else { return [] }
            let target = String(text[name.upperBound...])
            guard let list = slice(target, from: "resources: [", to: "]") else { return [] }
            return Set(
                quoted(list)
                    .filter { $0.hasPrefix("Resources/") }
                    .map { String($0.dropFirst("Resources/".count)) }
            )
        }
    }

    /// `PixelArtLoader.subdirectories`, as written in `EntryVisual.swift`.
    ///
    /// Parsed off disk for the reason every roster above is: the loader lives in
    /// `VinodexUI`, which no Linux gate can compile, and this suite's own header
    /// records that gap as real and uncovered. It is a text file either way.
    private static var loaderSearchPath: [String] {
        get throws {
            let text = try read("Sources", "VinodexUI", "EntryVisual.swift")
            guard let list = slice(text, from: "private static let subdirectories = [", to: "]") else { return [] }
            // **Keep only what can be a directory name.** `quoted` has no idea
            // what a comment is, and this is the most heavily annotated list in
            // the package — a paragraph per entry explaining why the order is
            // what it is. Prose about strings tends to quote them, and one of
            // those notes reads `so "first hit wins" stays a statement about
            // ordering`, which parses as a tenth search path. A directory name
            // here is a single bare word, so requiring that is enough to tell
            // the entries from the prose, and it fails loudly rather than
            // silently if a real entry ever stops looking like one.
            return quoted(list).filter { name in
                !name.isEmpty && name.allSatisfy { $0.isLetter || $0.isNumber }
            }
        }
    }

    /// Declared on the loader's search path but not yet drawn, so no directory
    /// exists and `.copy` would fail the build if `Package.swift` named one.
    ///
    /// A named exemption rather than a silent subtraction: the day either set is
    /// authored, the importer creates the directory, the equality below starts
    /// failing, and the fix is to add the `.copy` *and* delete the name from
    /// here. Both halves, which is what an exemption list is for.
    ///
    /// **Empty since 0.8.5 (F1), and that is the list working.** It held
    /// `StampArt` and `StickerArt` from the day it was written. Both were
    /// authored in this batch, both directories appeared, and the check at the
    /// bottom of `loaderSearchPathIsBundled` failed on exactly the two names —
    /// which is the entire reason an exemption is written as a two-way
    /// assertion rather than as a subtraction. Kept at zero entries rather than
    /// deleted: the next search path added ahead of its art needs somewhere to
    /// be declared, and a list that has been emptied once is a list somebody
    /// trusts.
    private static let unauthoredArtDirectories: Set<String> = []

    /// **Every bundled directory is declared, and nothing is declared twice over.**
    ///
    /// `Package.swift` used to say `.copy("Resources")` and pick up a new
    /// directory the moment an importer created one. The Aug 5 codesign fix had
    /// to stop doing that — a shallow iOS bundle whose root holds a folder named
    /// `Resources` is rejected by codesign — so the children are now listed by
    /// hand, and a hand-kept list of directories is precisely what this suite
    /// exists to police for scripts.
    ///
    /// It was already wrong when it arrived, through nobody's fault: `ButtonArt`
    /// (0.8.1), `FooterArt` and `CartridgeArt` (0.8.2) were being written on a
    /// batch branch while the list was written on another. A bundle missing them
    /// compiles, signs, installs and runs — and every drawn face, footer cap and
    /// cartridge silently falls back, because `PixelArtLoader` and `IconLoader`
    /// both return nil rather than throwing.
    @Test("every bundled resource directory is copied by Package.swift")
    func bundledArtDirectoriesAreRegistered() throws {
        let onDisk = try Self.bundledDirectoriesOnDisk
        let declared = try Self.packageResourceDirectories
        #expect(onDisk.count >= 10, "found only \(onDisk.sorted()) — did the slice parse?")
        #expect(!declared.isEmpty, "could not parse Package.swift's VinodexUI resource list")
        #expect(
            declared == onDisk,
            """
            Package.swift and Sources/VinodexUI/Resources/ disagree — \
            on disk but not bundled: \(onDisk.subtracting(declared).sorted()), \
            bundled but absent (this is a build error): \(declared.subtracting(onDisk).sorted())
            """
        )
    }

    /// **The loader searches only directories that will be in the bundle.**
    ///
    /// The other half of the same fault. A stem is looked up by walking this list,
    /// so a directory that ships but is never searched is art nobody can reach,
    /// and a directory that is searched but never ships is a lookup that always
    /// misses. Both are invisible at runtime.
    @Test("PixelArtLoader searches only directories that ship")
    func loaderSearchPathIsBundled() throws {
        let search = try Self.loaderSearchPath
        let declared = try Self.packageResourceDirectories
        #expect(search.count >= 8, "could not parse PixelArtLoader.subdirectories")

        for entry in search {
            // The prefix is the bug this whole merge was about: under the new
            // bundle layout `Resources/ButtonArt` resolves to nothing, and
            // `DexResources.url`'s fallback is a *root*-level lookup that cannot
            // find a nested file either. Nil, in silence, forever.
            #expect(
                !entry.hasPrefix("Resources/"),
                "PixelArtLoader searches '\(entry)' — the bundle has no Resources/ wrapper any more"
            )
            #expect(
                declared.contains(entry) || Self.unauthoredArtDirectories.contains(entry),
                "PixelArtLoader searches '\(entry)', which Package.swift does not bundle"
            )
        }

        // And the exemptions must still be exemptions: a directory that has been
        // drawn since this list was written is one Package.swift now has to name.
        let onDisk = try Self.bundledDirectoriesOnDisk
        for name in Self.unauthoredArtDirectories {
            #expect(
                !onDisk.contains(name),
                "\(name) now exists — bundle it in Package.swift and drop it from unauthoredArtDirectories"
            )
        }
    }

    /// **No stale `Resources/` prefix anywhere in the UI module.**
    ///
    /// The general form, swept textually, because the two tests above only see
    /// the lists — a one-off `DexResources.url(..., subdirectory: "Resources/X")`
    /// in a view body is reachable by neither. There were eleven such call sites
    /// before the merge and every one of them had to move.
    ///
    /// `VinodexCore` is deliberately not swept: its three JSON lookups still ask
    /// for `subdirectory: "Resources"` first and fall through to a bare
    /// `Bundle.module.url(forResource:withExtension:)`, which finds them because
    /// under the new layout those files sit at the bundle *root*. The art cannot
    /// use that trick — it is one level deeper — which is exactly why the fix had
    /// to touch the UI module and not this one.
    @Test("no VinodexUI lookup still asks for the Resources wrapper")
    func noPrefixedSubdirectoryLookupsSurvive() throws {
        let dir = Self.repoRoot
            .appendingPathComponent("Sources")
            .appendingPathComponent("VinodexUI")
        let files = try FileManager.default
            .contentsOfDirectory(atPath: dir.path)
            .filter { $0.hasSuffix(".swift") }
        #expect(files.count >= 20, "found only \(files.count) sources under Sources/VinodexUI")

        for file in files.sorted() {
            let text = try String(contentsOf: dir.appendingPathComponent(file), encoding: .utf8)
            let lines: [Substring] = text.split(separator: Character("\n"), omittingEmptySubsequences: false)
            for (offset, line) in lines.enumerated()
            where line.contains("subdirectory: \"Resources") && !line.contains("///") {
                Issue.record("\(file):\(offset + 1) still asks for the Resources/ wrapper: \(line.trimmingCharacters(in: .whitespaces))")
            }
        }
    }

    /// The per-importer convenience scripts. `npm run icons` chains all of them;
    /// these are how you re-run one while iterating on its art, and `import-logo-art`
    /// having none is half of why nothing noticed it was unwired.
    @Test("package.json exposes every importer as its own script")
    func npmScriptsCoverAll() throws {
        let commands = try Self.npmCommands
        for importer in try Self.importersOnDisk.sorted() {
            #expect(
                commands.contains { $0.contains(importer) },
                "no package.json script runs \(importer)"
            )
        }
        // The outline generator is not an importer — it writes *sources* under
        // `art/`, which `import-class-art.py` then converts — so it is outside
        // the four rosters above by construction. It still needs a way to be run
        // by someone who did not write it (0.8.0, A1).
        #expect(
            commands.contains { $0.contains("make-country-outlines.py") },
            "no package.json script runs the outline generator"
        )
    }

    // MARK: - The outline masters (0.8.0, A1; re-based 0.8.4, F1)

    /// Every outline master under `art/icons/entries/countries/`, by stem.
    private static var outlineMasters: Set<String> {
        get throws {
            let dir = repoRoot.appendingPathComponent("art/icons/entries/countries")
            let names = try FileManager.default.contentsOfDirectory(atPath: dir.path)
            return Set(
                names
                    .filter { $0.lowercased().hasSuffix(".png") }
                    .map { String($0.dropLast(4)) }
            )
        }
    }

    /// **Masters drawn ahead of the catalog**, named rather than subtracted.
    ///
    /// The 0.8.4 drop is forty-six countries and states; the catalog names
    /// thirty-three of them. The other thirteen are not clutter and not a
    /// mistake — they are the next thirteen places a region could land in, and
    /// wiring one is a single `COUNTRY_SHAPE_ICONS` row because the art and its
    /// fill colour are already here.
    ///
    /// It is an exemption list in `assertOutlineCoverage`'s sense and fails the
    /// same two ways: a stem here that the catalog starts drawing has to come
    /// out, and a stem here with no master on disk means art was deleted. That
    /// is what stops "drawn ahead" from becoming the excuse that any unused file
    /// in the directory is fine.
    private static let drawnAheadOutlines: Set<String> = [
        "arizona", "bosnia", "czechia", "idaho", "israel", "michigan",
        "missouri", "new-mexico", "serbia", "slovakia", "texas", "ukraine",
        "virginia",
    ]

    /// **Every outline the catalog draws has a master, and every master is
    /// either drawn or on the backlog.**
    ///
    /// This is the same two-way shape `assertOutlineCoverage` uses, one layer
    /// further back. That check asks "does this place have outline art"; this one
    /// asks "does that art exist on disk".
    ///
    /// **It used to check the rings, and 0.8.4 is why it cannot any more.**
    /// Through 0.8.3 every outline was rasterised from
    /// `scripts/country-outline-rings.py`, so "does that art have a master" and
    /// "is there an authored ring" were the same question. F1 replaced the whole
    /// directory with hand-drawn coastlines, which no ring describes — the rings
    /// survive as a fallback rasteriser and are no longer the art. Checking them
    /// now would be asserting a relationship the build does not have.
    ///
    /// The three spellings that made the old version necessary are also gone: a
    /// master's stem *is* its `art:outline-<stem>` id, so `import-class-art.py`
    /// resolves the source by rule and there is no filename table to drift.
    @Test("every drawn outline has a master, and every master is drawn or on the backlog")
    func outlineMastersMatchTheManifest() throws {
        let manifest = try Data(
            contentsOf: Self.repoRoot
                .appendingPathComponent("Sources/VinodexCore/Resources/icons.json")
        )
        let json = try JSONSerialization.jsonObject(with: manifest) as? [String: Any]
        let shapes = json?["countryShapeIcons"] as? [String: String] ?? [:]
        #expect(!shapes.isEmpty, "icons.json carries no countryShapeIcons")

        let wanted = Set(shapes.values.map { $0.replacingOccurrences(of: "art:outline-", with: "") })
        let masters = try Self.outlineMasters
        #expect(masters.count >= 30, "found only \(masters.count) outline masters — is the checkout complete?")

        #expect(
            wanted.subtracting(masters).isEmpty,
            """
            outlines the catalog draws with no master: \
            \(wanted.subtracting(masters).sorted()) — draw them into art/icons/entries/countries/
            """
        )
        #expect(
            masters.subtracting(wanted) == Self.drawnAheadOutlines,
            """
            the drawn-ahead backlog has drifted — \
            unlisted masters nothing draws: \(masters.subtracting(wanted).subtracting(Self.drawnAheadOutlines).sorted()), \
            listed but now drawn or deleted: \(Self.drawnAheadOutlines.subtracting(masters.subtracting(wanted)).sorted())
            """
        )
    }

    /// **Every master has an ink colour, and every ink colour has a master.**
    ///
    /// The masters are silhouettes — one flat cream shape each — and
    /// `import-class-art.py` paints them from `country-outline-fills.py` at
    /// import time (0.8.4, F1). A master with no row would import as a blank
    /// key error at art time on somebody's laptop; a row with no master is a
    /// colour chosen for a country that does not exist here.
    ///
    /// This is the check the fill table could not have before, when it was one
    /// argument to a rasteriser that only ever ran over its own thirty keys.
    @Test("every outline master has a fill colour, and every fill colour a master")
    func everyMasterHasAFill() throws {
        let source = try Self.read("scripts", "country-outline-fills.py")
        guard let table = Self.slice(source, from: "FILL = {", to: "}") else {
            Issue.record("could not parse FILL out of country-outline-fills.py")
            return
        }
        // Alternating stem, "#rrggbb" across the quoted runs.
        let quoted = Self.quoted(table)
        var fills: Set<String> = []
        for pair in stride(from: 0, to: quoted.count - 1, by: 2) {
            fills.insert(quoted[pair])
            #expect(
                quoted[pair + 1].hasPrefix("#") && quoted[pair + 1].count == 7,
                "\(quoted[pair]): '\(quoted[pair + 1])' is not a #rrggbb colour"
            )
        }
        #expect(!fills.isEmpty, "parsed no fill rows")

        let masters = try Self.outlineMasters
        #expect(
