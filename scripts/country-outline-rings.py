"""The authored lon/lat rings the country outlines are drawn from (0.8.0, A1).

**This file is master art.** Through 0.7.9 twenty-eight of the thirty outlines
were hand-drawn PNGs and two were rasterised by a throwaway script, so the
generator could honestly be called a one-shot. A1 makes all thirty derived, and
at that point the shape of every country in the app lives *here* -- there is no
other master to go back to. It is split out from `make-country-outlines.py` for
the same reason `SOURCE_FOR` is a table at the top of `import-class-art.py`: the
data is the part a person edits and the code is the part they do not.

**Coordinates, not pixels.** Each ring is a closed sequence of `(lon, lat)`
vertices in degrees, wound in either direction (the rasteriser is even-odd).
Islands are extra rings on the same key. The resolution to author to is set by
the canvas: at roughly 106 cells on the long axis a country the size of France
resolves to about 0.12 degrees per cell, so a ring of thirty to sixty vertices
is the useful range -- past that the detail lands inside one cell and past that
again it is a lie about how precise this is.

**The bounding box is the load-bearing part**, not the outline. `regions.ts`
authors `mapPosition` as fractions of the outline's own canvas and
`make-country-outlines.py` maps a canvas linearly onto the ring's bbox, so a
dot's fraction resolves to a real lon/lat through this table. Getting a
coastline slightly wrong moves a pixel; getting an extreme point wrong moves
every dot in the country. The `--check` pass exists because of that.

**Fill colours are flag-derived**, which is the rule 0.7.9 set with Brazil's
green and Mexico's red and which those two keep verbatim. Each outline is only
ever drawn alone in an icon well, so two countries sharing a colour costs
nothing and a country wearing somebody else's flag costs the whole point.
"""

